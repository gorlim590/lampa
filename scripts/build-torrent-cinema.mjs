// Dependency-free offline build. TVs receive the committed single artifact.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=file=>fs.readFileSync(path.join(root,file),'utf8');
const modules=['metadata','view','runtime','entry'];
const artifact='/* Generated by node scripts/build-torrent-cinema.mjs; edit ui/torrent-cinema/ sources. */\n(function(){\n\'use strict\';\nif(window.LampaTorrentCinema)return;\nvar CINEMA_CSS='+JSON.stringify(read('ui/torrent-cinema/style.css'))+';\n'+modules.map(name=>read('ui/torrent-cinema/'+name+'.js')).join('\n')+'\n})();\n';
const output=path.join(root,'ui/torrent-cinema.js');
if(process.argv.includes('--check')){
    if(!fs.existsSync(output)||fs.readFileSync(output,'utf8')!==artifact){console.error('Torrent Cinema artifact is stale; run node scripts/build-torrent-cinema.mjs');process.exitCode=1;}
}else fs.writeFileSync(output,artifact);
